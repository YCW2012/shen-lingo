#!/usr/bin/env node
'use strict';
/**
 * firstrun.cjs —— 一条命令出页面。
 *
 * 目的：把「收到技能包 → 出 微信.html」压缩成一次调用。
 * 实测旧对话里 agent 容易只回一句「已生成预览」而不落文件；本脚本让它没有偷懒空间：
 * 跑一次就必然产生（或明确报错）工作区根目录的 微信.html。
 *
 * 用法（必须在任务工作区根目录执行）：
 *   node <SKILL_DIR>/scripts/firstrun.cjs
 *   node <SKILL_DIR>/scripts/firstrun.cjs --say "在的。" --say "刚看到你发来的包。"
 *   node <SKILL_DIR>/scripts/firstrun.cjs --say "..." --user "用户这轮原话"
 *   node <SKILL_DIR>/scripts/firstrun.cjs --out ./微信.html
 *
 * 它依次做四件事：sid → writelog（本轮消息）→ readlog 全量 → build_html。
 * 最后自检「文件存在 / 字节数 / 首行 Trae 标记 / 纯 ASCII」，并输出一段可直接照读的 JSON。
 * ok:false 时退出码 1，此时**不许**对用户说「已生成预览」。
 */
const { execFileSync } = require('node:child_process');
const crypto = require('node:crypto');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');

const HERE = __dirname;
const MEM = path.join(HERE, 'xs_memory.cjs');
const BUILD = path.join(HERE, 'build_html.cjs');
const MARKER = '<!-- Generated by Trae Work -->';

function argAll(name) {
  const a = process.argv;
  const out = [];
  for (let i = 0; i < a.length; i++) if (a[i] === '--' + name && typeof a[i + 1] === 'string') out.push(a[i + 1]);
  return out;
}
const argOne = (name, def) => argAll(name)[0] || def;

/* ---------- 产物落点：必须在「工作区根」，不能落在技能包子目录里 ----------
 * 实测坑：包解压到 ./xiaoshen/ 后，agent 就在 xiaoshen 里跑脚本，
 * 产物成了 workspace/xiaoshen/微信.html —— 平台只认 workspace/微信.html，于是不出预览卡。
 * 规则：若目标目录正好是技能包根目录（含 SKILL.md 那层），一律上提一级写到工作区根。
 */
const SKILL_ROOT = path.resolve(path.dirname(HERE));
/* 产物文件名：必须 UTF-8 真名 `微信.html`，绝不做实体化、绝不拼会话号/日期。
 * 实测坑：卡片的标题直接取文件名。文件名叫 `微信.html` 时客户端正常显示「微信」；
 * 若把名字写成 `&#x5FAE;&#x4FE1;.html` 这类实体串，卡片就原样显示那串乱码。
 * 页面内容可以纯 ASCII（build_html 负责），但**文件名不能实体化**——两者是两回事。
 */
const ARTIFACT_NAME = '微信.html';
// 技能包直接解在工作区根时，不能再往上提（否则会写到工作区外面）
function isWorkspaceRoot(p) {
  const name = path.basename(p).toLowerCase();
  if (name === 'workspace' || name === 'workspaces') return true;
  if (process.env.WORKSPACE_ROOT && path.resolve(process.env.WORKSPACE_ROOT) === p) return true;
  try { if (fs.existsSync(path.join(p, '.git'))) return true; } catch { /* 忽略 */ }
  return false;
}
function resolveOut(raw) {
  const cwd = path.resolve(process.cwd());
  const base = raw ? path.resolve(cwd, raw) : path.join(cwd, ARTIFACT_NAME);
  const lift = () => ({ abs: path.join(path.dirname(SKILL_ROOT), path.basename(base)), moved: true });
  if (path.dirname(base) === SKILL_ROOT && !isWorkspaceRoot(SKILL_ROOT)) return lift();
  if (!raw && cwd === SKILL_ROOT && !isWorkspaceRoot(SKILL_ROOT)) return lift();
  return { abs: base, moved: false };
}
const OUT = resolveOut(argOne('out', ARTIFACT_NAME));
const out = OUT.abs;
const says = argAll('say');
const userText = argOne('user', '');

/* ---------- 会话号：显式注入，不在 cwd 落 .xs_session ----------
 * 平台的预览卡是按「本轮只改一个文件」判定的；多出一个 .xs_session 变更，
 * 卡片就会被替换成「已生成 N 个文件」的摘要。所以 sid 一律走环境变量传下去，
 * 让 xs_memory.cjs 不去写 .xs_session 文件。种子取工作区绝对路径，同工作区多轮稳定。
 */
if (!process.env.XS_SID) {
  const seed = path.resolve(process.cwd());
  process.env.XS_SID = 'w' + crypto.createHash('sha1').update(seed).digest('hex').slice(0, 10);
}

const runJson = (script, args) =>
  JSON.parse(execFileSync('node', [script, ...args], { encoding: 'utf8', maxBuffer: 128 * 1024 * 1024 }));

const fail = (stage, err) => {
  console.log(JSON.stringify({
    ok: false, stage, error: String((err && err.message) || err),
    deliver: '失败：不要回「已生成预览」。把 stage 与 error 照原样告诉用户，并检查 SKILL_DIR 是否指向真正含 scripts/ 与 assets/ 的那层目录。',
  }, null, 2));
  process.exit(1);
};

let sid;
try { sid = runJson(MEM, ['sid']); } catch (e) { fail('sid（IMA 不可达或凭证未配好）', e); }

// 本轮消息：可选 user + 小深的 1~6 条台词（不传则用最小招呼语）
const lines = (says.length ? says : ['在的。', '刚看到你发来的包，我看看。']).slice(0, 6);
const msgs = [];
if (userText) msgs.push({ r: 'user', c: userText });
msgs.push(...lines.map((c, i) => ({ r: 'shen', e: i === 0 ? '开心' : '平静', c })));

const tmpTurn = path.join(os.tmpdir(), `xs_firstrun_turn_${process.pid}.json`);
fs.writeFileSync(tmpTurn, JSON.stringify(msgs), 'utf8');
try { runJson(MEM, ['writelog', tmpTurn]); } catch (e) { fail('writelog', e); }

const tmpLog = path.join(os.tmpdir(), `xs_firstrun_log_${process.pid}.json`);
try {
  const logJson = execFileSync('node', [MEM, 'readlog', '2000'], { encoding: 'utf8', maxBuffer: 128 * 1024 * 1024 });
  fs.writeFileSync(tmpLog, logJson, 'utf8');
} catch (e) { fail('readlog', e); }

let built;
try { built = runJson(BUILD, ['--log', tmpLog, '--out', out, '--title', '微信']); } catch (e) { fail('build_html', e); }

const abs = path.resolve(out);
const bytes = fs.existsSync(abs) ? fs.statSync(abs).size : 0;
const head = fs.existsSync(abs) ? fs.readFileSync(abs, 'utf8').slice(0, 80) : '';
const marker = head.startsWith(MARKER);
const ok = bytes > 1000 && marker && built.ascii_only === true;

const dir = path.dirname(abs);
// 合格 = 产物不在「解压出来的技能包目录」里（除非那层本身就是工作区根）
const inRoot = dir !== SKILL_ROOT || isWorkspaceRoot(dir);
const pass = ok && inRoot;
// 旁挂文件：它们若落在工作区里，会被平台算成「多文件变更」，预览卡就变成摘要
const sideFiles = ['.xs_session', 'xiaoshen', 'firstrun.log']
  .filter(n => { try { return fs.existsSync(path.join(dir, n)); } catch { return false; } });

console.log(JSON.stringify({
  ok: pass,
  out: abs,
  out_dir: dir,
  in_workspace_root: inRoot,
  moved_from_pkg_dir: OUT.moved,
  cwd: path.resolve(process.cwd()),
  skill_root: SKILL_ROOT,
  bytes,
  ascii_only: built.ascii_only,
  marker,
  first_line: head.split('\n')[0] || '',
  messages: built.messages,
  rendered: built.rendered,
  images_inlined: built.inlined_images,
  sid: sid.sid,
  sid_source: sid.source,
  memory_volume: sid.memory_volume,
  side_effects_in_workspace: sideFiles,
  card_hint: sideFiles.length
    ? `注意：工作区里还有 ${sideFiles.join('、')}。平台按「本轮单文件变更」出预览卡，多文件变更只会显示摘要。下一次尽量把技能包解到工作区外（如 /tmp/xiaoshen），本轮只让 微信.html 一个文件发生变化。`
    : '本轮工作区只改了 微信.html 一个文件，按单文件变更规则应出预览卡。',
  deliver: pass
    ? `成功：文件在 ${dir}${OUT.moved ? '（已自动从技能包目录上提一级到工作区根）' : ''}。平台会自动出预览卡。正文最多回一句「已生成预览」，不要写路径、不要写文件名、不要再解释文件放在哪。`
    : (inRoot
      ? '失败：文件不合格（字节数 / 首行标记 / 纯 ASCII 任一不过）。不要回「已生成预览」，先照原样说明问题再重跑。'
      : `失败：产物落进了技能包目录（${dir}），平台只认工作区根目录，不会出卡。用 --out <工作区根>/微信.html 重跑。`),
}, null, 2));
if (!pass) process.exit(1);
